-- Baseline schema for the KSE password manager (PostgreSQL).
-- The server only ever stores ciphertext: encrypted_* columns hold AES-GCM
-- output produced in the browser; *_key columns hold RSA-OAEP-wrapped keys.

create table password_items (
    id                 uuid primary key,
    name               varchar(255)   not null,
    url                varchar(2048),
    username           varchar(255),
    encrypted_password varchar(4096)  not null,
    password_iv        varchar(255)   not null,
    encrypted_notes    varchar(16384),
    notes_iv           varchar(255),
    tags               varchar(1024),
    owner_email        varchar(255)   not null,
    item_type          varchar(255)   not null,
    sync_mode          varchar(255)   not null,
    created_at         timestamptz(6) not null,
    updated_at         timestamptz(6) not null
);

create index idx_password_items_owner on password_items (owner_email);

create table permissions (
    id           uuid primary key,
    item_id      uuid           not null references password_items (id),
    grantee_type varchar(255)   not null,
    grantee      varchar(255)   not null,
    role         varchar(255)   not null,
    granted_by   varchar(255)   not null,
    created_at   timestamptz(6) not null,
    constraint uq_permissions_item_grantee unique (item_id, grantee_type, grantee)
);

create index idx_permissions_grantee on permissions (grantee);

create table item_keys (
    id          uuid primary key,
    item_id     uuid           not null references password_items (id),
    user_email  varchar(255)   not null,
    wrapped_key varchar(4096)  not null,
    created_at  timestamptz(6) not null,
    constraint uq_item_keys_item_user unique (item_id, user_email)
);

create index idx_item_keys_user on item_keys (user_email);

create table user_keys (
    email                 varchar(255) primary key,
    public_key            varchar(2048)  not null,
    encrypted_private_key varchar(8192)  not null,
    private_key_iv        varchar(255)   not null,
    kdf_salt              varchar(255)   not null,
    created_at            timestamptz(6) not null,
    updated_at            timestamptz(6) not null
);

create table audit_events (
    id          bigint generated by default as identity primary key,
    occurred_at timestamptz(6) not null,
    actor_email varchar(255)   not null,
    action      varchar(255)   not null,
    item_id     uuid,
    item_name   varchar(255),
    target      varchar(255),
    details     varchar(1024)
);

create index idx_audit_events_occurred on audit_events (occurred_at desc);

create table user_settings (
    email                   varchar(255) primary key,
    default_sync_mode       varchar(255) not null,
    clipboard_clear_seconds integer      not null
);
